const text = (
  value: string,
  x: number,
  y: number,
  w: number,
  size: number,
  fill: string,
  extra: Partial<DesignElement> = {},
) =>
  el('text', {
    text: value,
    name: value.split('\n')[0].slice(0, 30),
    x,
    y,
    width: w,
    height: size * 1.3 * value.split('\n').length,
    fontSize: size,
    fontFamily: 'DM Sans',
    fontWeight: 400,
    lineHeight: 1.1,
    fill,
    ...extra,
  });
const rect = (
  x: number,
  y: number,
  width: number,
  height: number,
  fill: string,
  radius = 0,
  extra: Partial<DesignElement> = {},
) => el('rect', { x, y, width, height, fill, radius, ...extra });
const circle = (
  x: number,
  y: number,
  size: number,
  fill: string,
  extra: Partial<DesignElement> = {},
) => el('ellipse', { x, y, width: size, height: size, fill, ...extra });
function template(
  id: string,
  title: string,
  category: string,
  width: number,
  height: number,
  background: string,
  elements: DesignElement[],
): Template {
  return {
    id,
    title,
    category,
    width,
    height,
    color: background,
    page: { id: uid(), name: title, background, elements },
  };
}
